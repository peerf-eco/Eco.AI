def get_analyze_user_prompt(user_message: str) -> str:
    """Формирует пользовательский промпт для анализа"""
    return f"Запрос пользователя: {user_message}"


def get_generate_user_prompt(
    user_intent: str,
    platform: str,
    context: str
) -> str:
    """Формирует пользовательский промпт для генерации"""
    return f"""
Задача: {user_intent}
Платформа: {platform}

{context}

Сгенерируй полный рабочий код приложения, используя указанные компоненты.
Следуй ТОЧНО сигнатурам из заголовков!
"""


def get_review_user_prompt(headers_text: str, code: str) -> str:
    """Формирует пользовательский промпт для ревью"""
    return f"""
═══ ЗАГОЛОВКИ ═══
{headers_text}

═══ КОД ═══
{code}
"""

