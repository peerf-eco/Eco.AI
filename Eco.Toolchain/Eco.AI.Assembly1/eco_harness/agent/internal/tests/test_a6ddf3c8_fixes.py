def _write_trace(path: Path, input_tokens: int, *, cache_reported=None, cache_read=0):
    usage = {"input": input_tokens, "output": 1, "cacheRead": cache_read}
    if cache_reported is not None:
        usage["cacheReadReported"] = cache_reported
    path.write_text(
        json.dumps({"meta": {}, "response": {"usage": usage}}),
        encoding="utf-8",
    )


def test_run_metrics_isolates_sequence_and_unknown_cache_status(tmp_path: Path):
    from eco_harness.backend.server import _collect_run_metrics

    traces = tmp_path / "traces"
    traces.mkdir()
    _write_trace(traces / "001-architect.json", 60000,
                 cache_reported=True, cache_read=0)
    _write_trace(traces / "002-coder.json", 60000)
    _write_trace(traces / "003-tester.json", 60000,
                 cache_reported=True, cache_read=10)

    metrics = _collect_run_metrics(traces, start_sequence=1)
    assert metrics["calls"] == 2
    assert metrics["full_miss_calls"] == 0
    assert metrics["full_miss_tokens"] == 0
    assert metrics["cache_unknown_calls"] == 1
    assert metrics["cache_unknown_tokens"] == 60000


def test_run_metrics_counts_explicit_cache_miss(tmp_path: Path):
    from eco_harness.backend.server import _collect_run_metrics

